// Checks everything in specs/:
//
// 1. Specs: every specs/*.ts is compiled to TLA+ by tla-ts and model checked.
// 2. Modules: every hand-written specs/*.tla with a .cfg beside it is checked.
// 3. Mutants: every specs/*.mutants.mjs lists copies of a spec with one bug
//    planted. Each mutant names the one property that must catch it, and is
//    checked with only that property enabled, so the check proves that this
//    property, on its own, catches this bug.
// 4. Coverage: every invariant and temporal property of every spec and
//    module must be caught by at least one mutant. A property no mutant
//    breaks proves nothing.
//
// Usage: node scripts/check.mjs [name-filter]

import { spawn } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { availableParallelism, tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(fileURLToPath(import.meta.url), "../..");
const specsDir = join(root, "specs");
const cli = join(root, "node_modules/tla-ts/dist/cli.js");
const { compile } = await import(pathToFileURL(join(root, "node_modules/tla-ts/dist/compile.js")).href);

const GENERATED = "\\* Generated by tla-ts from";
const filter = process.argv[2];
const matches = (name) => !filter || name.toLowerCase().includes(filter.toLowerCase());

// ---------------------------------------------------------------------------

const run = (args, cwd) =>
  new Promise((done) => {
    const child = spawn(process.execPath, [cli, ...args], { cwd });
    let output = "";
    child.stdout.on("data", (chunk) => (output += chunk));
    child.stderr.on("data", (chunk) => (output += chunk));
    child.on("close", (status) => done({ status, output }));
  });

const pool = async (items, worker) => {
  const results = new Array(items.length);
  let next = 0;
  const lanes = Math.max(1, Math.min(items.length, Math.floor(availableParallelism() / 2)));
  await Promise.all(
    Array.from({ length: lanes }, async () => {
      while (next < items.length) {
        const index = next++;
        results[index] = await worker(items[index]);
      }
    }),
  );
  return results;
};

const VIOLATION =
  /Error: (?:Invariant \w+ is violated|Action property \w+[^\n]* is violated|Temporal propert(?:y \w+ was|ies were) violated)/;

const firstError = (output) =>
  output.split("\n").find((line) => line.startsWith("Error:") || /Tla\w*Error/.test(line)) ??
  "no error reported";

const states = (output) => [...output.matchAll(/([\d,]+) distinct states found/g)].at(-1)?.[1];

// INVARIANTS and PROPERTIES named in a config, and the rest of its lines.
const readConfig = (text) => {
  const invariants = [];
  const properties = [];
  const rest = [];
  let section;
  for (const line of text.split("\n")) {
    const words = line.replace(/\\\*.*$/, "").trim().split(/\s+/).filter(Boolean);
    if (words.length === 0) continue;
    if (/^[A-Z_]+$/.test(words[0])) {
      section = words[0];
      if (section === "INVARIANT" || section === "INVARIANTS") invariants.push(...words.slice(1));
      else if (section === "PROPERTY" || section === "PROPERTIES") properties.push(...words.slice(1));
      else rest.push(line);
    } else if (section === "INVARIANT" || section === "INVARIANTS") invariants.push(...words);
    else if (section === "PROPERTY" || section === "PROPERTIES") properties.push(...words);
    else rest.push(line);
  }
  return { invariants, properties, rest };
};

const onlyProperty = (configText, property) => {
  const { invariants, properties, rest } = readConfig(configText);
  if (invariants.includes(property)) return [...rest, `INVARIANT ${property}`].join("\n");
  if (properties.includes(property)) return [...rest, `PROPERTY ${property}`].join("\n");
  return undefined;
};

const moduleName = (file) =>
  basename(file, ".ts")
    .split(/[^A-Za-z0-9]+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");

let failures = 0;
const report = (ok, label, detail = "") => {
  console.log(`${ok ? "✓" : "✗"} ${label}${detail && !ok ? `\n    ${detail}` : ""}`);
  if (!ok) failures++;
};

// ---------------------------------------------------------------------------
// 1. Specs written in TypeScript

const entries = readdirSync(specsDir)
  .filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts"))
  .sort();

console.log("Specs");
const specResults = await pool(entries.filter(matches), async (entry) => {
  const { status, output } = await run(["-workers", "1", entry], specsDir);
  return { entry, ok: status === 0 && output.includes("No error has been found"), output };
});
for (const { entry, ok, output } of specResults) {
  const count = states(output);
  report(ok, `${entry}${count ? ` (${count} distinct states)` : ""}`, firstError(output));
}

// ---------------------------------------------------------------------------
// 2. Hand-written TLA+ modules with a config

const modules = readdirSync(specsDir)
  .filter(
    (f) =>
      f.endsWith(".tla") &&
      existsSync(join(specsDir, f.replace(/\.tla$/, ".cfg"))) &&
      !readFileSync(join(specsDir, f), "utf8").startsWith(GENERATED),
  )
  .sort();

console.log("\nModules");
const moduleResults = await pool(modules.filter(matches), async (module) => {
  const { status, output } = await run(["-workers", "1", module], specsDir);
  return { module, ok: status === 0 && output.includes("No error has been found"), output };
});
for (const { module, ok, output } of moduleResults) {
  const count = states(output);
  report(ok, `${module}${count ? ` (${count} distinct states)` : ""}`, firstError(output));
}

// ---------------------------------------------------------------------------
// 3. Mutants

const mutantFiles = readdirSync(specsDir)
  .filter((f) => f.endsWith(".mutants.mjs"))
  .sort();

const mutants = [];
for (const file of mutantFiles) {
  const list = (await import(pathToFileURL(join(specsDir, file)).href)).default;
  const base = file.replace(/\.mutants\.mjs$/, "");
  for (const mutant of list) {
    const target = mutant.file ?? `${base}.ts`;
    // The module whose config decides which properties exist: a hand-written
    // module when the mutant names one, otherwise the mutated spec itself.
    const checked = mutant.module ?? (target.endsWith(".ts") ? `${moduleName(target)}.tla` : target);
    mutants.push({ ...mutant, source: file, target, checked });
  }
}

const runMutant = async (mutant) => {
  const dir = mkdtempSync(join(tmpdir(), "graphql-tla-"));
  try {
    cpSync(specsDir, dir, { recursive: true });
    const targetPath = join(dir, mutant.target);
    const original = readFileSync(targetPath, "utf8");
    if (!original.includes(mutant.find)) return { ok: false, detail: `can't find: ${mutant.find}` };
    const mutated = original.replace(mutant.find, mutant.replace);
    writeFileSync(targetPath, mutated);

    let configText;
    if (mutant.target.endsWith(".ts")) {
      const compiled = compile(mutated, targetPath);
      writeFileSync(join(dir, `${compiled.name}.tla`), `${compiled.source}\n`);
      if (!mutant.module) configText = compiled.config;
    }
    if (configText === undefined) {
      configText = readFileSync(join(dir, mutant.checked.replace(/\.tla$/, ".cfg")), "utf8");
    }
    const config = onlyProperty(configText, mutant.property);
    if (config === undefined) {
      return { ok: false, detail: `${mutant.checked} has no property ${mutant.property}` };
    }
    writeFileSync(join(dir, "Mutant.cfg"), `${config}\n`);
    const { output } = await run(["-workers", "1", "-config", "Mutant.cfg", mutant.checked], dir);
    const violation = output.match(VIOLATION);
    return { ok: violation !== null, detail: firstError(output) };
  } catch (error) {
    return { ok: false, detail: String(error.message ?? error).split("\n")[0] };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

console.log("\nMutants");
const selected = mutants.filter((m) => matches(m.source) || matches(m.checked));
const mutantResults = await pool(selected, runMutant);
selected.forEach((mutant, index) => {
  const { ok, detail } = mutantResults[index];
  report(ok, `${mutant.checked}: ${mutant.name} → caught by ${mutant.property}`, detail);
});

// ---------------------------------------------------------------------------
// 4. Every property is caught by some mutant

console.log("\nCoverage");
const configs = [
  ...entries.map((e) => `${moduleName(e)}.cfg`),
  ...modules.map((m) => m.replace(/\.tla$/, ".cfg")),
].filter((c) => matches(c) && existsSync(join(specsDir, c)));
for (const config of configs) {
  const { invariants, properties } = readConfig(readFileSync(join(specsDir, config), "utf8"));
  const module = config.replace(/\.cfg$/, ".tla");
  const caught = new Set(mutants.filter((m) => m.checked === module).map((m) => m.property));
  const missing = [...invariants, ...properties].filter((p) => !caught.has(p));
  report(
    missing.length === 0,
    `${module}: ${invariants.length + properties.length} properties, each caught by a mutant`,
    `no mutant for: ${missing.join(", ")}`,
  );
}

if (failures > 0) {
  console.error(`\n${failures} check(s) failed`);
  process.exit(1);
}
